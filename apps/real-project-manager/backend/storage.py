"""Persistent SQLite command bridge for the real project-manager reference app.

This is trusted scaffolding, NOT output generated by Qwen2.5-Coder-0.5B.
Node calls one JSON command per Python process. All SQL is parameterized.
"""
from __future__ import annotations

from datetime import datetime, timezone
import json
import os
from pathlib import Path
import sqlite3
import sys
import uuid


STATUSES = ("todo", "doing", "done")
PRIORITIES = ("low", "medium", "high")


def stamp():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def string(data, name, max_len=160, allow_empty=False):
    value = data.get(name)
    if not isinstance(value, str):
        raise ValueError(f"{name} must be text")
    value = value.strip()
    if not allow_empty and not value:
        raise ValueError(f"{name} cannot be empty")
    if len(value) > max_len:
        raise ValueError(f"{name} exceeds {max_len} characters")
    return value


def one(connection, query, params=()):
    row = connection.execute(query, params).fetchone()
    return dict(row) if row else None


def rows(connection, query, params=()):
    return [dict(row) for row in connection.execute(query, params).fetchall()]


def initialize(connection):
    connection.executescript("""
        PRAGMA foreign_keys = ON;
        CREATE TABLE IF NOT EXISTS projects (
            id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            description TEXT NOT NULL DEFAULT '',
            color TEXT NOT NULL DEFAULT '#5c8cff',
            created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS tasks (
            id TEXT PRIMARY KEY,
            project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
            title TEXT NOT NULL,
            description TEXT NOT NULL DEFAULT '',
            status TEXT NOT NULL DEFAULT 'todo' CHECK(status IN ('todo','doing','done')),
            priority TEXT NOT NULL DEFAULT 'medium' CHECK(priority IN ('low','medium','high')),
            due_date TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_tasks_project ON tasks(project_id);
    """)


def overview(connection, _payload):
    return {
        "projects": rows(connection, "SELECT * FROM projects ORDER BY created_at, name"),
        "tasks": rows(connection, "SELECT * FROM tasks ORDER BY created_at DESC"),
    }


def dispatch(connection, action, data):
    if action == "overview":
        return overview(connection, data)
    if action == "create_project":
        name = string(data, "name", 80)
        description = string({"description": data.get("description", "")},
                             "description", 500, allow_empty=True)
        color = data.get("color", "#5c8cff")
        if not isinstance(color, str) or len(color) != 7 or color[0] != "#" or any(
            char not in "0123456789abcdefABCDEF" for char in color[1:]
        ):
            raise ValueError("color must be a six-digit hex value")
        project = {"id": str(uuid.uuid4()), "name": name,
                   "description": description, "color": color,
                   "created_at": stamp()}
        connection.execute("INSERT INTO projects VALUES (:id,:name,:description,:color,:created_at)", project)
        return project
    if action == "delete_project":
        pid = string(data, "id", 80)
        result = connection.execute("DELETE FROM projects WHERE id=?", (pid,))
        if not result.rowcount:
            raise LookupError("Project not found")
        return {"deleted": pid}
    if action == "update_project":
        pid = string(data, "id", 80)
        current = one(connection, "SELECT * FROM projects WHERE id=?", (pid,))
        if current is None:
            raise LookupError("Project not found")
        if "name" in data:
            current["name"] = string(data, "name", 80)
        if "description" in data:
            current["description"] = string(data, "description", 500, allow_empty=True)
        connection.execute("UPDATE projects SET name=?,description=? WHERE id=?",
                           (current["name"], current["description"], pid))
        return one(connection, "SELECT * FROM projects WHERE id=?", (pid,))
    if action == "create_task":
        pid = string(data, "project_id", 80)
        if not one(connection, "SELECT id FROM projects WHERE id=?", (pid,)):
            raise LookupError("Project not found")
        status = data.get("status", "todo")
        priority = data.get("priority", "medium")
        if status not in STATUSES or priority not in PRIORITIES:
            raise ValueError("Invalid status or priority")
        task = {"id": str(uuid.uuid4()), "project_id": pid,
                "title": string(data, "title"),
                "description": string({"description": data.get("description", "")},
                                      "description", 1000, allow_empty=True),
                "status": status, "priority": priority,
                "due_date": data.get("due_date") or None,
                "created_at": stamp(), "updated_at": stamp()}
        if task["due_date"] is not None and (not isinstance(task["due_date"], str)
                                             or len(task["due_date"]) != 10):
            raise ValueError("due_date must be a YYYY-MM-DD string")
        connection.execute("""INSERT INTO tasks
            (id,project_id,title,description,status,priority,due_date,created_at,updated_at)
            VALUES (:id,:project_id,:title,:description,:status,:priority,:due_date,:created_at,:updated_at)""", task)
        return task
    if action == "update_task":
        tid = string(data, "id", 80)
        current = one(connection, "SELECT * FROM tasks WHERE id=?", (tid,))
        if current is None:
            raise LookupError("Task not found")
        for field, limit in (("title", 160), ("description", 1000)):
            if field in data:
                current[field] = string(data, field, limit, allow_empty=field == "description")
        for field, options in (("status", STATUSES), ("priority", PRIORITIES)):
            if field in data:
                if data[field] not in options:
                    raise ValueError(f"Invalid {field}")
                current[field] = data[field]
        if "due_date" in data:
            due = data["due_date"]
            if due is not None and (not isinstance(due, str) or len(due) != 10):
                raise ValueError("due_date must be a YYYY-MM-DD string")
            current["due_date"] = due
        current["updated_at"] = stamp()
        connection.execute("""UPDATE tasks SET title=:title,description=:description,
            status=:status,priority=:priority,due_date=:due_date,updated_at=:updated_at
            WHERE id=:id""", current)
        return one(connection, "SELECT * FROM tasks WHERE id=?", (tid,))
    if action == "delete_task":
        tid = string(data, "id", 80)
        result = connection.execute("DELETE FROM tasks WHERE id=?", (tid,))
        if not result.rowcount:
            raise LookupError("Task not found")
        return {"deleted": tid}
    raise ValueError("Unknown action")


def execute(command, database):
    if not isinstance(command, dict) or not isinstance(command.get("payload", {}), dict):
        raise ValueError("Invalid command")
    database.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(database, timeout=8) as connection:
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA busy_timeout=8000")
        initialize(connection)
        result = dispatch(connection, command.get("action"), command.get("payload", {}))
        connection.commit()
        return result


def main():
    try:
        command = json.load(sys.stdin)
        db_path = Path(os.environ.get("PROJECT_DB_PATH", "/data/project-manager.sqlite"))
        result = {"ok": True, "data": execute(command, db_path)}
    except (ValueError, LookupError, sqlite3.Error) as error:
        result = {"ok": False, "error": str(error),
                  "kind": "not_found" if isinstance(error, LookupError) else "validation"}
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
