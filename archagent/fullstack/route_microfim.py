# ------------------------------------------------------------- ledger

def update_ledger(fn) -> None:
    data = json.loads(LEDGER.read_text()) if LEDGER.exists() else \
        {"files": {}, "stages": [], "model_usage_cumulative": {}}
    fn(data)
    LEDGER.write_text(json.dumps(data, indent=1))


def main() -> None:
    t_start = time.time()
    devserver.stop_dev()
    time.sleep(2)
    model = FrozenModel(threads=2)
    log(f"model loaded in {time.time() - t_start:.0f}s; "
        f"usage={model.usage()}")

    # ---------------- phase 1: route-list micro-FIM ladder ----------
    base = derive_base()
    log(f"base derived: {len(base.splitlines())} lines, "
        f"{len(base)} chars (from route-list_r0_k3, mechanical)")
    offs = line_offsets(base)
    fills: dict = {}
    patch_meta: dict = {}
    for p in PATCHES:
        fill, meta = run_patch(model, base, p, offs)
        if fill is not None:
            fills[p["pid"]] = fill
            patch_meta[p["pid"]] = meta
    merged = apply_patches(base, fills)
    missing = [p["pid"] for p in PATCHES if p["pid"] not in fills]
    log(f"patches landed: {len(fills)}/{len(PATCHES)}"
        + (f"  MISSING: {missing}" if missing else ""))
    target = install.APP / "src/app/api/items/route.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(merged if merged.endswith("\n") else merged + "\n")
    (GEN / "route-list_merged.ts").write_text(merged)
    log("route-list merged file installed + archived")

    # ---------------- phase 2: route-id assembly --------------------
    get_src = json.loads((GEN / "body_route-id_get_r0_k1.json").read_text())
    del_src = json.loads(
        (GEN / "body_route-id_delete_r0_k1.json").read_text())
    get_body = cut_body_at_prose(get_src["processed"])
    del_body = cut_body_at_prose(del_src["processed"])
    log(f"archived bodies cut: get {len(get_body.splitlines())} lines, "
        f"delete {len(del_body.splitlines())} lines")
    put_body, put_meta = gen_put_body(model)
    if put_body is None:
        log("PUT BODY FAILED after 3x4 — route-id cannot be assembled")
        put_body = "  // PUT BODY GENERATION FAILED (see generations/)"
    id_file = (ID_HEAD + get_body.rstrip() + ID_MID1 + put_body.rstrip()
               + ID_MID2 + del_body.rstrip() + TAIL)
    t2 = install.APP / "src/app/api/items/[id]/route.ts"
    t2.parent.mkdir(parents=True, exist_ok=True)
    t2.write_text(id_file if id_file.endswith("\n") else id_file + "\n")
    (GEN / "route-id_merged.ts").write_text(id_file)
    log("route-id assembled file installed + archived")

    usage = dict(model.usage())
    log(f"model usage this run: {usage}")

    # ---------------- phase 3: unload, static gates ------------------
    del model
    gc.collect()
    time.sleep(2)
    results = {}
    for cid in ("route-list", "route-id"):
        contract = next(c for c in CONTRACTS if c["id"] == cid)
        ok, fb = runner_d.run_gates(contract, True)
        results[cid] = dict(ok=ok, feedback=fb)
        log(f"GATES {cid}: ok={ok}")
        if not ok:
            log("  feedback: " + fb[:500].replace("\n", "\n  "))

    # ---------------- phase 4: ledger --------------------------------
    def record(data: dict) -> None:
        data["files"]["src/app/api/items/route.ts"] = dict(
            contract="route-list", label="QWEN-REPAIRED",
            base="route-list_r0_k3 (QWEN-ORIGINAL bytes, mechanical "
                 "strip+trim)",
            patches=patch_meta,
            missing=missing,
            note=("9-region micro-FIM ladder; per-patch samples in "
                  "generations/route-list_fimp_*.json"))
        if put_body and "FAILED" not in put_body:
            data["files"]["src/app/api/items/[id]/route.ts"] = dict(
                contract="route-id", label="QWEN-REPAIRED",
                bodies=dict(
                    get=dict(src="body_route-id_get_r0_k1", cut="prose"),
                    put=put_meta,
                    delete=dict(src="body_route-id_delete_r0_k1",
                                cut="prose")),
                note=("GET/DELETE bodies are unmodified QWEN-ORIGINAL "
                      "bytes (mechanical trailing-prose cut); PUT body "
                      "from body-contract; skeleton lines are disclosed "
                      "interface scaffolding"))
        data["stages"].append(dict(
            contract="route-microfim", accepted=all(
                r["ok"] for r in results.values()) and not missing,
            gates=results, usage_run=usage, missing=missing))
        c = data.setdefault("model_usage_cumulative", {})
        c["generations"] = c.get("generations", 0) + usage["generations"]
        c["total_new_tokens"] = (c.get("total_new_tokens", 0)
                                 + usage["total_new_tokens"])
    update_ledger(record)

    # ---------------- phase 5: dynamic apitest (as frozen) -----------
    devserver.start_dev()
    log("== apitest (frozen, as-committed) ==")
    try:
        r = subprocess.run(["node", str(EXP / "apitest.mjs")],
                           capture_output=True, text=True, timeout=600,
                           env=NODE_ENV, cwd=str(EXP))
        log(r.stdout)
        if r.stderr.strip():
            log("stderr: " + r.stderr[-500:])
    except subprocess.TimeoutExpired:
        log("apitest TIMEOUT")

    log(f"runner complete in {time.time() - t_start:.0f}s")


if __name__ == "__main__":
    main()
