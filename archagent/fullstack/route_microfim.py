def cut_body_at_prose(text: str) -> str:
    """Mechanical trailing-prose cut for archived body samples: keep
    leading code lines; stop at the first numbered-item / narrative /
    repetition marker line.  No code line is ever altered."""
    lines = text.splitlines()
    keep = []
    for ln in lines:
        s = ln.strip()
        if (re.match(r"^\d+\.\s", s) or s.startswith("The handler")
                or s.startswith("The next task") or s.startswith("I wrote")
                or s.startswith("And the second line")
                or s.startswith("Note:") or s.startswith("```")
                or s.startswith("Write the body")):
            break
        keep.append(ln)
    # drop trailing blank lines
    while keep and not keep[-1].strip():
        keep.pop()
    return "\n".join(keep)


def gen_put_body(model) -> tuple[str | None, dict]:
    """PUT body via completion-mode body contract, 3 rounds x 4 samples
    with failure feedback between rounds."""
    feedback = None
    own_prev = None
    for round_no in range(3):
        parts = [PUT_CONCEPT, "", PUT_DEMO, "",
                 f"Now YOUR task.  {PUT_SPEC}"]
        if own_prev:
            parts += ["", "Your previous body (which failed the checks) "
                           "was:", own_prev[-800:]]
        if feedback:
            parts += ["", "The automated checks reported:", feedback[-700:],
                      "Fix exactly that."]
        parts += ["", "Write the body now.  The first line is already "
                      "written; continue from it:", PUT_ANCHOR]
        prompt = "\n".join(parts)
        for k in range(4):
            seed = (k * 1013 + round_no * 77) or 7
            stochastic = k != 0
            text, usage = model.generate(prompt, max_tokens=450,
                                         seed=seed, stochastic=stochastic)
            comp = strip_prompt_echo(text.strip("\n"), prompt)
            reasons = []
            for w in DEMO_ECHO:
                if w in comp:
                    reasons.append(f"demo echo {w!r}")
            body = PUT_ANCHOR + comp
            for need in ["db.inventoryItem.update", ".catch",
                         "'not found'", "Number.isInteger"]:
                if need not in body:
                    reasons.append(f"missing {need!r}")
            if not merged_balance_ok(body + "\n}\n"):
                reasons.append("brace imbalance")
            ok = not reasons
            (GEN / f"route-id_put_r{round_no}_k{k}.json").write_text(
                json.dumps(dict(kind="body", contract="route-id",
                                step="put", round=round_no, k=k, seed=seed,
                                usage=usage, prompt=prompt, completion=text,
                                processed=body, reject=reasons or None),
                           ensure_ascii=False, indent=1))
            log(f"  [put r{round_no} k{k}] seed={seed} "
                f"tok={usage['tokens']} ok={ok} "
                f"{('; '.join(reasons))[:120]}")
            if ok:
                return body, dict(round=round_no, k=k, seed=seed,
                                  tokens=usage["tokens"])
        own_prev = comp
        feedback = "last sample rejected: " + "; ".join(reasons)
    return None, {}


