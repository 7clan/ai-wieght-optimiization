def line_offsets(text: str) -> list[int]:
    offs = [0]
    for i, ch in enumerate(text):
        if ch == "\n":
            offs.append(i + 1)
    return offs  # offs[n] = start offset of line n+1


def merged_balance_ok(text: str) -> bool:
    depth = 0
    in_str = None
    i = 0
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 2
                continue
            if c == in_str:
                in_str = None
        elif c in "\"'`":
            in_str = c
        elif c == "/" and i + 1 < len(text) and text[i + 1] == "/":
            j = text.find("\n", i)
            if j == -1:
                break
            i = j
        elif c in "{([":
            depth += 1
        elif c in "})]":
            depth -= 1
            if depth < 0:
                return False
        i += 1
    return depth == 0


def apply_patches(base: str, fills: dict) -> str:
    offs = line_offsets(base)
    regions = []
    for p in PATCHES:
        if p["pid"] not in fills:
            continue
        regions.append((offs[p["a"] - 1], offs[p["b"] - 1],
                        p["pid"], fills[p["pid"]]))
    regions.sort(key=lambda r: (r[0], r[1]))
    out = []
    pos = 0
    for start, end, pid, fill in regions:
        out.append(base[pos:start])
        f = fill.strip("\n")
        if f:
            out.append(f + "\n")
        pos = end
    out.append(base[pos:])
    return "".join(out)


def run_patch(model, base: str, p: dict, offs: list[int]) -> tuple[str | None, dict]:
    """Up to 3 FIM samples for one region; archive every sample."""
    prefix = base[:offs[p["a"] - 1]]
    suffix = base[offs[p["b"] - 1]:]
    for k in range(3):
        seed = k * 1013 or 7
        stochastic = k != 0
        text, usage = model.fim(prefix=prefix, suffix=suffix,
                                instructions=p["instr"],
                                max_tokens=p["tok"], seed=seed,
                                stochastic=stochastic)
        fill = text.strip("\n")
        reasons = []
        for w in DEMO_ECHO:
            if w in fill:
                reasons.append(f"demo echo {w!r}")
        if "```" in fill:
            reasons.append("markdown fence")
        if len(fill.splitlines()) > 20:
            reasons.append("too long")
        for rx in p["expect"]:
            if not re.search(rx, fill):
                reasons.append(f"expect {rx} missing")
        cand = apply_patches(base, {p["pid"]: fill})
        if not merged_balance_ok(cand):
            reasons.append("merged brace imbalance")
        ok = not reasons
        (GEN / f"route-list_fimp_{p['pid']}_k{k}.json").write_text(
            json.dumps(dict(kind="fim-patch", pid=p["pid"], k=k, seed=seed,
                            usage=usage, prefix_tail=prefix[-400:],
                            suffix_head=suffix[:200], instructions=p["instr"],
                            completion=text, reject=reasons or None),
                       ensure_ascii=False, indent=1))
        log(f"  [fimp {p['pid']} k{k}] seed={seed} tok={usage['tokens']} "
            f"ok={ok} {('; '.join(reasons))[:120]}")
        if ok:
            return fill, dict(pid=p["pid"], k=k, seed=seed,
                              tokens=usage["tokens"])
    return None, {}


