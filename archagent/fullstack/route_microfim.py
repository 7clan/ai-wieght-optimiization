"""Micro-FIM patch ladder for the route stage (Session 035, cont.).

Evidence base (all archived under experiments/zai-fullstack/generations/):
- whole-file route contracts: 3x4 rounds -> demo echoes, prompt echoes,
  documentation-only completions, ONE near-miss (route-list r0_k3)
- FIM with ~90-word instructions: instruction echo (route-list_fim_*)
- FIM with an 11-word instruction, 15-token fill: surgical success
  (schema sku nullability, schema_fim_k1)
- body-granularity completion contracts: correct id-get / id-delete
  bodies produced; PUT invalid; list-GET where-object never correct

Method here: the near-miss r0_k3 (QWEN-ORIGINAL bytes after the
mechanical strip+trim pipeline) is the BASE.  Nine disjoint regions of
that base are re-generated by native FIM, one small gap per call, each
with a <= ~15-word instruction sitting at the end of the prefix
(measured adjacency).  Regions are defined by LINE OFFSETS in the
original base, so every patch sees the original context and all fills
merge mechanically.  route-id is assembled from the two archived
correct bodies (mechanical prose cut) plus a PUT body generated by the
body-contract machinery with execution feedback.

Provenance: base bytes + fills = QWEN-REPAIRED (per-patch seeds and
token counts recorded); skeletons/anchors = disclosed interface
scaffolding.  Nothing in this module authors application bytes.
"""
