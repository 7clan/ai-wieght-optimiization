"""Provenance-checked publisher for actual FIM output and static preview."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil

from .session022_contract import SLOTS, TEMPLATES, assemble
from .session015 import MODEL_PARAMETER_COUNT
from .session014 import MODEL_ID
from .rome20 import save_json

ROLES={'logic':'backend/logic.py','api':'server/routes.js',
       'ui':'client/App.jsx','css':'client/style.css'}


def collect(out, gallery, experiments, readme):
    report=json.loads((out/'report.json').read_text(encoding='utf-8'))
    predictions=json.loads((out/'predictions.json').read_text(encoding='utf-8'))
    slots=predictions['slots']
    if (report['session']!='022' or report['model']!=MODEL_ID or
        report['parameter_count']!=MODEL_PARAMETER_COUNT or
        report['training_steps']!=0 or report['weight_edits']!=0 or
        set(slots)!=set(SLOTS) or report['model_owned_slots']!=list(SLOTS) or
        report['generated_candidate_count']!=len(predictions['records']) or
        report['holdout_consulted_during_selection'] is not False):
        raise ValueError('Model provenance or evaluation identity is invalid')
    for role,src in assemble(slots).items():
        if (src!=predictions['source'][role] or
            src!=(out/'generated'/ROLES[role]).read_text(encoding='utf-8') or
            predictions['scaffold_sha256'][role]!=hashlib.sha256(TEMPLATES[role].encode()).hexdigest()):
            raise ValueError('Actual saved source differs from measured model slots')
    checks=report['selected']['holdout']
    if report['integrated_model_assisted_app_pass'] != (
        checks['integrated'] and all(report['slot_success'].values())):
        raise ValueError('False integrated passing claim')
    if checks['integrated'] and not all(x['passed'] for x in checks['modules'].values()):
        raise ValueError('Inconsistent Docker integrated result')
    page=(out/'preview'/'index.html').read_text(encoding='utf-8')
    if '<script' in page.lower() or '<iframe' in page.lower():
        raise ValueError('Unsafe preview HTML')
    if gallery.exists():raise FileExistsError('Destination preview already exists')
    gallery.mkdir(parents=True)
    shutil.copy2(out/'preview'/'index.html',gallery/'index.html')
    for role,path in ROLES.items():
        dst=gallery/'generated'/path
        dst.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(out/'generated'/path,dst)
    save_json(experiments/'session022_fim_app_report.json',report)
    save_json(experiments/'session022_fim_app_predictions.json',predictions)
    status='PASS' if report['integrated_model_assisted_app_pass'] else 'FAIL'
    slot_rows='\n'.join(f'| {name} | {"PASS" if report["slot_success"][name] else "FAIL"} |'
                         for name in SLOTS)
    section=f'''## Session 022 — Qwen0.5B native FIM, real application integration

**End-to-end sandbox contract: {status}.** Qwen2.5-Coder-0.5B filled eight
small code slots in a separately authored functional React/Express/Python
application scaffold. The code outside those slots was **not generated by
Qwen**. A passing result demonstrates *model-assisted assembly*, not an
autonomous senior-developer-level model.

| Model-filled code slot | Public acceptance |
| --- | --- |
{slot_rows}

[View actual model code and static UI snapshot](docs/previews/session022/index.html)
· [Exact prompt completions](experiments/session022_fim_app_predictions.json)
· [Verified report](experiments/session022_fim_app_report.json).

The visual snapshot is a sanitized document, not a hosted Express server.
There is no claim of browser end-to-end reliability or production readiness.
'''
    contents=readme.read_text(encoding='utf-8')
    marker='# TinyCoder Weight Lab\n'
    if not contents.startswith(marker) or '## Session 022 —' in contents:
        raise ValueError('Unexpected README state')
    readme.write_text(contents.replace(marker,marker+'\n'+section+'\n',1),encoding='utf-8')
    print(json.dumps({'status':status,'model_slots':report['slot_success']}),flush=True)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output-dir',type=Path,default=Path('outputs/session022'))
    a=p.parse_args()
    collect(a.output_dir,Path('docs/previews/session022'),Path('experiments'),Path('README.md'))


if __name__=='__main__':main()
