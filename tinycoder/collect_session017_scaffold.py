"""Check and publish Session017b verified scaffold-ablation comparisons."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .rome20 import save_json
from .session017 import metrics
from .session017_contracts import contract_sha256, contracts


def collect(out:Path, directory:Path, readme:Path):
    report=json.loads((out/"report.json").read_text(encoding="utf-8"))
    predictions=json.loads((out/"predictions.json").read_text(encoding="utf-8"))
    tasks=contracts()
    ids=[t["task_id"] for t in tasks]
    if (report.get("status")!="completed" or report.get("session")!="017b"
        or report.get("manifest_sha256")!=contract_sha256(tasks)
        or report.get("task_ids")!=ids
        or report["selection"]["number_of_new_model_inference_calls"]!=0
        or report["selection"]["holdout_used_for_selection"] is not False):
        raise ValueError("Scaffold report provenance invalid")
    for track in ("baseline", "guided"):
        if set(predictions[f"{track}_scaffold"]) != set(ids):
            raise ValueError("Missing predicted source bundles")
        rows=report["task_results"][track]
        if [x["task_id"] for x in rows]!=ids or metrics(rows)!=report[f"{track}_scaffold"]:
            raise ValueError("Scaffold metrics did not reproduce")
    directory.mkdir(parents=True,exist_ok=True)
    save_json(directory/"session017_scaffold_report.json",report)
    save_json(directory/"session017_scaffold_predictions.json",predictions)
    current=readme.read_text(encoding="utf-8")
    start,end="<!-- SESSION017B-PENDING-START -->","<!-- SESSION017B-PENDING-END -->"
    if current.count(start)!=1 or current.count(end)!=1:
        raise ValueError("Missing unique README pending scaffold block")
    b,g=report["baseline"],report["guided"]
    bs,gs=report["baseline_scaffold"],report["guided_scaffold"]
    block=f"""## Session 017b — contract-derived React scaffold (measured)

**No new model inference or edits.** Reused the exact Session017 frozen
Qwen2.5-Coder-0.5B Python/Express/React completions. A deterministic
`ResultView` implementation derived from the public app contract was
substituted **only where the original generated React component failed public
checks**. The complete app was then re-evaluated on the SAME holdout cases.
Unchanged Python/Express modules and unmodified final tests isolate the effect
of moving trivial UI structure to trusted deterministic scaffolding.

| System | Integrated holdout apps | Python modules | Express modules | React modules |
| --- | ---: | ---: | ---: | ---: |
| Greedy generated-only | {b['full_app_passes']}/10 | {b['module_passes']['logic']}/10 | {b['module_passes']['api']}/10 | {b['module_passes']['ui']}/10 |
| Guided generated-only | {g['full_app_passes']}/10 | {g['module_passes']['logic']}/10 | {g['module_passes']['api']}/10 | {g['module_passes']['ui']}/10 |
| Greedy + contract UI scaffold | {bs['full_app_passes']}/10 | {bs['module_passes']['logic']}/10 | {bs['module_passes']['api']}/10 | {bs['module_passes']['ui']}/10 |
| Guided + contract UI scaffold | {gs['full_app_passes']}/10 | {gs['module_passes']['logic']}/10 | {gs['module_passes']['api']}/10 | {gs['module_passes']['ui']}/10 |

**Caution:** Scaffold-assisted code is NOT independently generated by the
0.5B model, and these are custom, small application slices—not production
software or an independent frontier-model comparison. A passing score is not
a security, accessibility, or deployment audit. Candidate code remains
untrusted and is executed only in isolated, network-disabled Docker.

[Verified scaffold report](experiments/session017_scaffold_report.json) ·
[Exact scaffolded source outputs](experiments/session017_scaffold_predictions.json).

"""
    prefix,rest=current.split(start,1)
    _,suffix=rest.split(end,1)
    readme.write_text(prefix+block+suffix.lstrip("\n"),encoding="utf-8")
    print(json.dumps({k:report[k]["full_app_passes"] for k in
                      ("baseline","guided","baseline_scaffold","guided_scaffold")}),flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir",type=Path,default=Path("outputs/session017b"))
    parser.add_argument("--publish-to",type=Path,default=Path("experiments"))
    parser.add_argument("--readme",type=Path,default=Path("README.md"))
    args=parser.parse_args()
    collect(args.output_dir,args.publish_to,args.readme)


if __name__=="__main__":
    main()
