def run(args):
    require_sandbox()
    root=Path(args.output_dir)
    if root.exists() and any(root.iterdir()):
        raise FileExistsError("Prior output exists")
    root.mkdir(parents=True,exist_ok=True)
    prior=json.loads(Path(args.lesson_predictions).read_text(encoding="utf8"))
    teacher=teacher_examples(prior)
    started=time.monotonic()
    model,tokenizer=_torch_model()
    count=sum(p.numel() for p in model.parameters())
    if count!=MODEL_PARAMETER_COUNT:
        raise RuntimeError("Unexpected student model capacity")
    baseline={}
    attempts=[]
    tokens=0
    for i,role in enumerate(ROLES):
        head=prompt(role)
        raw,n=generate_one(model,tokenizer,head,max_tokens=LIMITS[role],
                           seed=BASE_SEED+i,stochastic=False)
        baseline[role]=PREFIX[role]+raw
        attempts.append({"stage":"baseline","role":role,"prompt":head,"raw":raw,
                         "output_tokens":n})
        tokens+=n
        print(json.dumps({"baseline":role,"tokens":n}),flush=True)
    baseline_public=evaluate(baseline,PUBLIC,"public")
    selected=dict(baseline)
    public=baseline_public
    for round_ in range(2):
        for i,role in enumerate(ROLES):
            if public["modules"][role]["passed"]:
                continue
            student_error=public["modules"][role]["error"]
            head=prompt(role,teacher=teacher[role],error=student_error if round_ else "")
            raw,n=generate_one(model,tokenizer,head,max_tokens=LIMITS[role],
                   seed=BASE_SEED+100+round_*17+i,stochastic=round_>0)
            tokens+=n
            challenger=dict(selected)
            challenger[role]=PREFIX[role]+raw
            result=evaluate(challenger,PUBLIC,"public")
            accepted=metric(result,role)>metric(public,role)
            attempts.append({"stage":"mentor-example" if round_==0 else "feedback-repair",
                 "round":round_,"role":role,"prompt":head,"raw":raw,
                 "output_tokens":n,"accepted":accepted,"public_result":result["modules"][role],
                 "candidate_source":challenger[role]})
            if accepted:selected,public=challenger,result
            print(json.dumps({"role":role,"round":round_,"tokens":n,
                 "passed":result["modules"][role]["passed"],
                 "accepted":accepted,"error":result["modules"][role]["error"]}),flush=True)
    del model
    gc.collect()
    # Protected holdout first accessed here, after every public choice freezes.
    holdout_cases=holdout()
    base_hold=evaluate(baseline,holdout_cases,"holdout")
    selected_hold=evaluate(selected,holdout_cases,"holdout")
    selected_public=evaluate(selected,PUBLIC,"public")
    report={"session":"030","status":"completed","model":MODEL_ID,
        "parameter_count":count,"training_steps":0,"weight_edits":0,
        "new_application":NAME,"contract_sha256":fingerprint(),
        "target_app_modules_from_qwen":list(ROLES),
        "teacher_supplied_exact_target_solutions":False,
        "other_domain_teacher_examples":list(teacher),
        "teacher_patterns":REASONING_RULES,
        "permanent_weight_learning":False,
        "trusted_scaffold":["file signatures/imports","evaluation","preview"],
        "baseline":{"public":baseline_public,"holdout":base_hold},
        "guided":{"public":selected_public,"holdout":selected_hold},
        "search":{"candidate_count":len(attempts),"output_tokens":tokens,
                  "wall_seconds":round(time.monotonic()-started,2),
                  "private_holdout_seen_during_selection":False},
        "ui_browser_clicks_verified":False,"production_ready":False}
    save_json(root/"report.json",report)
    save_json(root/"predictions.json",{"greedy":baseline,"selected":selected,
        "attempts":attempts,"source_sha256":{r:hashlib.sha256(selected[r].encode()).hexdigest()
                                          for r in ROLES}})
    for role,path in ROLE_PATHS.items():
        target=root/"generated"/path
        target.parent.mkdir(parents=True,exist_ok=True)
        target.write_text(selected[role],encoding="utf8")
    preview(selected,selected_hold,root/"preview/index.html")
    print(json.dumps({"baseline_integrated":base_hold["integrated"],
                      "guided_integrated":selected_hold["integrated"],
                      "passes":{r:v["passed"] for r,v in selected_hold["modules"].items()},
                      "candidates":len(attempts)}),flush=True)


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--lesson-predictions",default="experiments/session028_mentor_predictions.json")
    p.add_argument("--output-dir",default="outputs/session030")
    run(p.parse_args())


if __name__=="__main__":
    main()
