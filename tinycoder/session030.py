IMAGE="tinycoder-session030-transfer:1"
LIMITS={"logic":290,"store":950,"api":700,"ui":1200,"css":380}
BASE_SEED=2026113000


def teacher_examples(previous):
    return {"logic":previous["selected"]["logic"],
            "store":STORE,"api":API,"ui":UI,
            "css":previous["selected"]["css"]}


def evaluate(modules,cases,phase,*,timeout=52):
    require_sandbox()
    if set(modules)!=set(ROLES) or phase not in ("public","holdout"):
        raise ValueError("Invalid evaluator request")
    with tempfile.TemporaryDirectory(prefix="qwen030-") as dirname:
        root=Path(dirname)
        inp,output=root/"input",root/"output"
        inp.mkdir(mode=0o755);output.mkdir(mode=0o777)
        os.chmod(root,0o755);os.chmod(output,0o777)
        req=inp/"input.json"
        req.write_text(json.dumps({"modules":modules,"cases":cases,"phase":phase}),encoding="utf8")
        os.chmod(req,0o644)
        name="qwen030-"+uuid.uuid4().hex[:12]
        try:
            proc=subprocess.run(docker_command(IMAGE,inp,output,name,is_web=True),
                capture_output=True,text=True,timeout=timeout,check=False)
        except subprocess.TimeoutExpired:
            subprocess.run(["docker","rm","-f",name],capture_output=True,timeout=8,check=False)
            return failure(phase,"Bounded isolated Docker timeout")
        record=output/"result.json"
        if proc.returncode or not record.is_file():
            return failure(phase,"Isolated evaluator error: "+proc.stderr[-220:])
        result=json.loads(record.read_text(encoding="utf8"))
        if result.get("phase")!=phase or set(result.get("modules",{}))!=set(ROLES):
            raise RuntimeError("Evaluator identity mismatch")
        return result


def metric(report,role):
    entry=report["modules"][role]
    role_checks={"logic":(),"store":("persistence","store_delete"),
                 "api":("get","post","summary","delete"),
                 "ui":("ui_wiring",),"css":()}[role]
    return (int(entry["passed"]),sum(bool(report["checks"].get(x)) for x in role_checks),
            int(entry["syntax_valid"]))


