"""Session 031: contract-first repair of Qwen's already-tested ShelfStock app.

This is an exploratory regression/repair exercise, NOT independent transfer:
the ShelfStock public and holdout tests were already used in Session 030.
Every replacement module must be freshly generated by the frozen Qwen model.
"""
from __future__ import annotations

import argparse
import gc
import hashlib
import json
from pathlib import Path
import time

from .rome20 import save_json
from .session014 import MODEL_ID, _torch_model
from .session015 import MODEL_PARAMETER_COUNT
from .session021 import generate_one
from .session027 import ROLE_PATHS
from .session030 import BASE_SEED, LIMITS, evaluate, metric, preview
from .session030_contract import GOALS, PREFIX, PUBLIC, ROLES, holdout


# Explicit target-specific contracts are instructions, never pasted solutions.
# The model must generate all executable bodies on its own.
CONTRACTS = {
    "logic": (
        "Input key is items, NEVER expenses. Each item has units (not amount_cents) "
        "and section (not category). Required output keys are count, total_units, "
        "by_section. For empty items return count=0, total_units=0, by_section={}. "
        "Add each item's units to total_units and by_section[item.section]."
    ),
    "store": (
        "Expose EXACTLY three methods: list(), create(body), delete(id). "
        "list() returns a JSON array. Missing file means []; mutation writes "
        "JSON array to file. create takes name, units, section; validates name "
        "and integer units>0; generates string id. delete compares string IDs "
        "and persists after successful removal. All methods stay in returned object."
    ),
    "api": (
        "Keep factory createApp(store,processor), routes GET/POST/DELETE on "
        "/api/items and GET /api/summary, and JSON envelopes exactly as specified."
    ),
    "ui": (
        "This is ShelfStock INVENTORY, not PocketLedger expenses. Display "
        "visible 'ShelfStock' heading and item name/units inputs. useState "
        "for items, summary, name, units, section. useEffect loads GET "
        "/api/items and GET /api/summary. Form submit POSTs name/units/section, "
        "and Delete button DELETEs by item ID. Refresh after both mutations. "
        "Render actual items and section totals. Do not display expenses, "
        "amount_cents, PocketLedger, or /api/expenses."
    ),
    "css": "Responsive CSS for inventory dashboard only."
}


def lesson_prompt(role: str, feedback: str) -> str:
    """Small-model-friendly instructions with a strict output boundary."""
    if role not in ROLES:
        raise ValueError(role)
    comment = "#" if role == "logic" else "/*" if role == "css" else "//"
    suffix = " */" if role == "css" else ""
    def line(message: str) -> str:
        return f"{comment} {message}{suffix}\n"
    lines = ["SESSION 031: implement the NEW ShelfStock contract, not the old app.",
             *GOALS[role].splitlines(),
             "CHECKLIST (all conditions are mandatory):", CONTRACTS[role],
             "Previous public failure: " + " ".join(feedback.split())[:280],
             "Think about method names, input/output keys and data flow first.",
             "Emit only executable completion after the signature. No markdown."]
    return "".join(line(x) for x in lines) + PREFIX[role]


def run(args):
    from .sandbox_eval import require_sandbox
    require_sandbox()
    destination = Path(args.output_dir)
    if destination.exists() and any(destination.iterdir()):
        raise FileExistsError("Existing Session031 output will not be overwritten")
    prior = json.loads(Path(args.prior_predictions).read_text(encoding="utf8"))
    sources = dict(prior["selected"])
    if set(sources) != set(ROLES):
        raise ValueError("Missing original Qwen modules")
    original = dict(sources)
    started = time.monotonic()
    before = evaluate(original, PUBLIC, "public")
    model, tokenizer = _torch_model()
    count = sum(p.numel() for p in model.parameters())
    if count != MODEL_PARAMETER_COUNT:
        raise RuntimeError("Unexpected frozen model size")
    attempts = []
    token_count = 0
    for index, role in enumerate(ROLES):
        if before["modules"][role]["passed"]:
            continue
        error = before["modules"][role].get("error") or "public contract failed"
        prompt = lesson_prompt(role, error)
        raw, tokens = generate_one(model, tokenizer, prompt,
                                  max_tokens=LIMITS[role],
                                  seed=BASE_SEED + 310 + index,
                                  stochastic=False)
        token_count += tokens
        candidate = PREFIX[role] + raw
        changed = dict(sources)
        changed[role] = candidate
        graded = evaluate(changed, PUBLIC, "public")
        accepted = metric(graded, role) > metric(before, role)
        attempts.append({"role": role, "prompt": prompt, "raw": raw,
                         "candidate_source": candidate, "tokens": tokens,
                         "accepted": accepted,
                         "public_result": graded["modules"][role]})
        if accepted:
            sources, before = changed, graded
        print(json.dumps({"role": role, "accepted": accepted,
                          "public_pass": graded["modules"][role]["passed"]}),
              flush=True)
    del model
    gc.collect()
    # The holdout is already consumed. Report it explicitly as a repeated test.
    initial_hold = evaluate(original, holdout(), "holdout")
    repaired_hold = evaluate(sources, holdout(), "holdout")
    destination.mkdir(parents=True, exist_ok=True)
    report = {"session": "031", "status": "completed", "model": MODEL_ID,
              "parameter_count": count, "training_steps": 0, "weight_edits": 0,
              "independent_generalization": False,
              "evaluation_note": "ShelfStock was consumed in Session030; repeated exploratory holdout",
              "teacher_target_code_used": False,
              "before": initial_hold, "after": repaired_hold,
              "public_after": before,
              "search": {"candidates": len(attempts), "tokens": token_count,
                         "seconds": round(time.monotonic()-started, 2)}}
    save_json(destination / "report.json", report)
    save_json(destination / "predictions.json",
              {"initial": original, "selected": sources, "attempts": attempts,
               "source_sha256": {r: hashlib.sha256(sources[r].encode()).hexdigest()
                                 for r in ROLES}})
    for role, path in ROLE_PATHS.items():
        target = destination / "generated" / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(sources[role], encoding="utf8")
    preview(sources, repaired_hold, destination / "preview" / "index.html")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--prior-predictions", default="experiments/session030_transfer_predictions.json")
    parser.add_argument("--output-dir", default="outputs/session031")
    run(parser.parse_args())


if __name__ == "__main__":
    main()
